export type IdPrefix = keyof typeof ID_PREFIXES;
export const ID_PREFIX_LIST = Object.keys(ID_PREFIXES) as IdPrefix[];

/** Branded ID type: `Id<"nov">` is a string known to be `nov_<ULID>`. */
export type Id<P extends IdPrefix> = `${P}_${string}` & { readonly __idBrand?: P };

export const CROCKFORD_ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";
export const ULID_REGEX_SOURCE = "[0-9A-HJKMNP-TV-Z]{26}";
const ULID_RE = new RegExp(`^${ULID_REGEX_SOURCE}$`);
const ID_RE = /^([a-z]{3})_([0-9A-HJKMNP-TV-Z]{26})$/;

const TIME_LEN = 10;
const RAND_LEN = 16;
const MAX_TIME = 2 ** 48 - 1;

function encodeTime(ms: number): string {
  if (!Number.isInteger(ms) || ms < 0 || ms > MAX_TIME) throw new RangeError(`ULID time out of range: ${ms}`);
  let out = "";
  let t = ms;
  for (let i = 0; i < TIME_LEN; i++) {
    const mod = t % 32;
    out = CROCKFORD_ALPHABET[mod] + out;
    t = (t - mod) / 32;
  }
  return out;
}

/** 80 random bits → 16 base32 chars, represented as digit array (each 0..31) for monotonic increments. */
function randomDigits(): number[] {
  const bytes = new Uint8Array(RAND_LEN);
  globalThis.crypto.getRandomValues(bytes); // Web Crypto: Node ≥19 and browsers
  return Array.from(bytes, (b) => b & 31);
}

function digitsToString(d: number[]): string {
  return d.map((x) => CROCKFORD_ALPHABET[x]).join("");
}

export interface UlidFactory {
  (nowMs?: number): string;
}

/**
 * Monotonic ULID factory: within the same millisecond the random part is incremented,
 * so IDs generated by one process sort in generation order.
 */
export function monotonicUlidFactory(clock: () => number = Date.now): UlidFactory {
  let lastTime = -1;
  let lastRand: number[] = [];
  return (nowMs?: number) => {
    const now = nowMs ?? clock();
    if (now <= lastTime && lastRand.length === RAND_LEN) {
      // increment random part (base32 digits, carry from the right)
      const next = lastRand.slice();
      let i = RAND_LEN - 1;
      while (i >= 0) {
        if (next[i]! < 31) {
          next[i] = next[i]! + 1;
          break;
        }
        next[i] = 0;
        i--;
      }
      if (i < 0) throw new Error("ULID random component overflow within one millisecond");
      lastRand = next;
      return encodeTime(lastTime) + digitsToString(next);
    }
    lastTime = now;
    lastRand = randomDigits();
    return encodeTime(now) + digitsToString(lastRand);
  };
}

const defaultUlid = monotonicUlidFactory();

/**
 * New ULID. Without `nowMs` the process-wide monotonic generator is used (IDs sort in creation order).
 * With an explicit `nowMs` (e.g. from a FakeClock) the timestamp is honoured exactly and the
 * random part is fresh (no monotonic guarantee against other calls).
 */
export function ulid(nowMs?: number): string {
  if (nowMs === undefined) return defaultUlid();
  return encodeTime(nowMs) + digitsToString(randomDigits());
}

export function isUlid(value: unknown): value is string {
  return typeof value === "string" && ULID_RE.test(value);
}

/** Decode the millisecond timestamp encoded in a ULID. */
export function ulidTime(value: string): number {
  if (!isUlid(value)) throw new TypeError(`Not a ULID: ${value}`);
  let t = 0;
  for (let i = 0; i < TIME_LEN; i++) t = t * 32 + CROCKFORD_ALPHABET.indexOf(value[i]!);
  return t;
}

export function isIdPrefix(value: unknown): value is IdPrefix {
  return typeof value === "string" && Object.hasOwn(ID_PREFIXES, value);
}

/** Generate a new ID with the given prefix. */
export function newId<P extends IdPrefix>(prefix: P, nowMs?: number): Id<P> {
  if (!isIdPrefix(prefix)) throw new TypeError(`Unknown ID prefix: ${String(prefix)}`);
  return `${prefix}_${ulid(nowMs)}` as Id<P>;
}

export interface ParsedId<P extends IdPrefix = IdPrefix> {
  prefix: P;
  ulid: string;
  type: (typeof ID_PREFIXES)[P];
  timestampMs: number;
}

/** Parse `<prefix>_<ULID>`; returns null when malformed or the prefix is unknown. */
export function parseId(value: unknown): ParsedId | null {
  if (typeof value !== "string") return null;
  const m = ID_RE.exec(value);
  if (!m) return null;
  const prefix = m[1]!;
  if (!isIdPrefix(prefix)) return null;
  const u = m[2]!;
  return { prefix, ulid: u, type: ID_PREFIXES[prefix], timestampMs: ulidTime(u) };
}

/** Is `value` a well-formed ID (optionally of a given prefix)? */
export function isId<P extends IdPrefix>(value: unknown, prefix?: P): value is Id<P> {
  const parsed = parseId(value);
  if (!parsed) return false;
  return prefix === undefined || parsed.prefix === prefix;
}

/** Assert and narrow; throws TypeError on mismatch. */
export function assertId<P extends IdPrefix>(value: unknown, prefix: P): Id<P> {
  if (!isId(value, prefix)) throw new TypeError(`Invalid ${prefix} id: ${String(value)}`);
  return value;
}

/** Regex source used by DB CHECK constraints: `^<prefix>_[0-9A-HJKMNP-TV-Z]{26}$`. */
export function idPatternFor(prefix: IdPrefix): string {
  return `^${prefix}_${ULID_REGEX_SOURCE}$`;
}
